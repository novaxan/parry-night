using NightShift;
using UnityEngine;
using System.Linq;
var nm = NightManager.Instance;
var gun = Object.FindFirstObjectByType<Shotgun>();
nm.BeginNight();
int before = gun.Model.Reserve;
nm.DebugSetElapsed(179.8f);
await Wait.Until(() => nm.Hour == 3);
float u = Time.unscaledTime + 0.6f;
await Wait.Until(() => Time.unscaledTime > u);
ScreenCapture.CaptureScreenshot("Screenshots/10_supply_drop.png");
int after = gun.Model.Reserve;
u = Time.unscaledTime + 0.3f;
await Wait.Until(() => Time.unscaledTime > u);
foreach (var r in nm.Robots) r.Brain.Place(0);
nm.DebugSetElapsed(359.8f);
await Wait.Until(() => nm.State == GameState.Won);
u = Time.unscaledTime + 0.5f;
await Wait.Until(() => Time.unscaledTime > u);
ScreenCapture.CaptureScreenshot("Screenshots/11_won.png");
return $"reserve {before}->{after}; state={nm.State}; {nm.EndReason}";
