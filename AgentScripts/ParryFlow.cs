using NightShift;
using UnityEngine;
using System.Linq;
using System.Reflection;
var log = new System.Text.StringBuilder();
var nm = NightManager.Instance;
var view = Object.FindFirstObjectByType<OfficeView>();
var gun = Object.FindFirstObjectByType<Shotgun>();
var flags = BindingFlags.NonPublic | BindingFlags.Instance;
nm.BeginNight();
var tusk = nm.Robots.First(r => r.Data.displayName == "Tusk");
foreach (var r in nm.Robots) if (r != tusk) { r.Brain.Place(0); }
tusk.Brain.Place(tusk.Brain.OpeningIndex);
typeof(OfficeView).GetMethod("Turn", flags).Invoke(view, new object[] { -1 });
await Wait.Until(() => tusk.Brain.State == RobotState.Telegraph && tusk.Brain.StateTimer < 0.35f);
ScreenCapture.CaptureScreenshot("Screenshots/03_telegraph.png");
log.Append($"telegraph ok; ");
await Wait.Until(() => tusk.Brain.InParryWindow || tusk.Brain.State == RobotState.Attacked);
log.Append($"window={tusk.Brain.InParryWindow} t={tusk.Brain.StateTimer:F3}; ");
typeof(Shotgun).GetMethod("Parry", flags).Invoke(gun, null);
log.Append($"after parry={tusk.Brain.State}; ");
float until = Time.unscaledTime + 0.5f;
await Wait.Until(() => Time.unscaledTime > until);
ScreenCapture.CaptureScreenshot("Screenshots/04_parried.png");
until = Time.unscaledTime + 0.3f;
await Wait.Until(() => Time.unscaledTime > until);
typeof(Shotgun).GetMethod("Fire", flags).Invoke(gun, null);
log.Append($"after shot={tusk.Brain.State} hp={tusk.Brain.Health} loaded={gun.Model.Loaded}; ");
until = Time.unscaledTime + 0.8f;
await Wait.Until(() => Time.unscaledTime > until);
ScreenCapture.CaptureScreenshot("Screenshots/05_killed.png");
log.Append($"kills={nm.Kills} gameState={nm.State}");
return log.ToString();
