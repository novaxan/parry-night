using NightShift;
using UnityEngine;
using System.Reflection;
var nm = NightManager.Instance;
nm.BeginNight(); nm.DebugFreezeRobots = true;
var gun = Object.FindFirstObjectByType<Shotgun>();
var flags = BindingFlags.NonPublic | BindingFlags.Instance;
typeof(Shotgun).GetMethod("Fire", flags).Invoke(gun, null);
await Wait.Until(() => !gun.Model.IsBusy);
typeof(Shotgun).GetMethod("Fire", flags).Invoke(gun, null);
await Wait.Until(() => !gun.Model.IsBusy);
typeof(Shotgun).GetMethod("Reload", flags).Invoke(gun, null);
await Wait.Until(() => gun.Model.Current == ShotgunModel.GunState.Reloading && gun.Model.ActionTimer < 0.9f * 0.75f);
ScreenCapture.CaptureScreenshot("Screenshots/v2_16_reload_rise.png");
await Wait.Until(() => gun.Model.ActionTimer < 0.9f * 0.5f);
ScreenCapture.CaptureScreenshot("Screenshots/v2_17_reload_lineup.png");
await Wait.Until(() => gun.Model.ActionTimer < 0.9f * 0.3f);
ScreenCapture.CaptureScreenshot("Screenshots/v2_18_reload_push.png");
await Wait.Until(() => gun.Model.Current == ShotgunModel.GunState.Idle);
return $"loaded={gun.Model.Loaded}";
